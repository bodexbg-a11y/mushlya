def base_offers():
    s = open(FEED_IN, encoding='utf-8').read()
    out = {}
    for o in re.findall(r'<offer [^>]*>(.*?)</offer>', s, re.S):
        code = re.search(r'<vendorCode>(.*?)</vendorCode>', o).group(1)
        out[code] = {
            'price': int(re.search(r'<price>(.*?)</price>', o).group(1)),
            'pictures': re.findall(r'<picture>(.*?)</picture>', o),
        }
    return out


